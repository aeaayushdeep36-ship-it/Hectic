/**
 * Reproducible Lighthouse accessibility gate.
 *
 * Starts the already-built Next app on an isolated port, runs Lighthouse
 * against the real dashboard, requires an accessibility score above 95, writes
 * the observed score to docs/lighthouse-a11y.md, then stops every child it
 * started. No dev server is left behind on success or failure.
 */
import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { chromium } from "@playwright/test";
import * as chromeLauncher from "chrome-launcher";
import lighthouse from "lighthouse";

const PORT = 4317;
const URL = `http://127.0.0.1:${PORT}/`;
const MIN_SCORE = 0.95;

const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function waitForServer(timeoutMs = 30_000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(URL);
      if (response.ok) return;
    } catch {
      // The server is still starting.
    }
    await wait(250);
  }
  throw new Error(`Next server did not become ready at ${URL}`);
}

const server = spawn(
  process.execPath,
  [path.join("node_modules", "next", "dist", "bin", "next"), "start", "-p", String(PORT)],
  {
    cwd: process.cwd(),
    stdio: ["ignore", "pipe", "pipe"],
    env: { ...process.env, PORT: String(PORT) },
  },
);
let serverOutput = "";
server.stdout.on("data", (chunk) => {
  serverOutput += String(chunk);
});
server.stderr.on("data", (chunk) => {
  serverOutput += String(chunk);
});

let chrome;
try {
  await waitForServer();
  chrome = await chromeLauncher.launch({
    chromePath: chromium.executablePath(),
    chromeFlags: ["--headless", "--no-sandbox", "--disable-gpu", "--disable-dev-shm-usage"],
  });
  const result = await lighthouse(URL, {
    port: chrome.port,
    onlyCategories: ["accessibility"],
    output: "json",
    logLevel: "error",
  });
  const lhr = result.lhr;
  const score = lhr.categories.accessibility?.score ?? 0;
  const failures = Object.values(lhr.audits)
    .filter((audit) => audit.score !== null && audit.score < 1)
    .map((audit) => {
      const snippets = (audit.details?.items ?? [])
        .map((item) => item.node?.snippet)
        .filter(Boolean)
        .slice(0, 5);
      return [
        `- ${audit.id}: ${audit.title} (${audit.score})`,
        ...snippets.map((snippet) => `  - \`${String(snippet).slice(0, 240)}\``),
      ].join("\n");
    });
  const passed = score > MIN_SCORE;
  const lines = [
    "# Lighthouse accessibility gate",
    "",
    `Generated by \`npm run a11y:lighthouse\` on ${new Date().toISOString()}.`,
    "",
    `| Target | Score | Required | Result |`,
    `|---|---:|---:|---|`,
    `| \`${URL}\` | ${Math.round(score * 100)} | >95 | ${passed ? "PASS" : "FAIL"} |`,
    "",
    "## Audits below 100",
    "",
    ...(failures.length ? failures : ["None."]),
    "",
  ];
  writeFileSync(path.join("docs", "lighthouse-a11y.md"), lines.join("\n"));

  console.log(`Lighthouse accessibility: ${Math.round(score * 100)} (required >95)`);
  if (!passed) {
    console.error(lines.join("\n"));
    process.exitCode = 1;
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  console.error(serverOutput.slice(-4000));
  process.exitCode = 1;
} finally {
  if (chrome) {
    try {
      chrome.kill();
    } catch {
      // The browser may already have exited.
    }
  }
  server.kill("SIGTERM");
  await wait(250);
  if (!server.killed) server.kill("SIGKILL");
}
