/**
 * Reproducible 20-row workflow timer used by TIME_SAVED_REPORT.md.
 *
 * Starts the already-built app on an isolated port, uploads the first 20
 * interview rows from fixtures/clean/roster.csv, then completes the real UI
 * path: preview → run → named agent stream → falsifier → export. The median of
 * three browser runs is written to docs/time-saved-measurement.md. The server
 * and browser are always stopped in the finally block.
 */
import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { chromium } from "@playwright/test";

const PORT = 4319;
const URL = `http://127.0.0.1:${PORT}/`;
const ITERATIONS = 3;
const FALSIFIER =
  "This claim dies if a cold budget holder signs a paid pilot within 30 days without prompting.";
const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function waitForServer(timeoutMs = 30_000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      if ((await fetch(URL)).ok) return;
    } catch {
      // Still starting.
    }
    await wait(250);
  }
  throw new Error(`Next server did not become ready at ${URL}`);
}

const server = spawn(
  process.execPath,
  [path.join("node_modules", "next", "dist", "bin", "next"), "start", "-p", String(PORT)],
  { cwd: process.cwd(), stdio: "ignore" },
);
let browser;
try {
  await waitForServer();
  browser = await chromium.launch({ headless: true });
  const csv = readFileSync(path.join("fixtures", "clean", "roster.csv"), "utf8")
    .split(/\r?\n/)
    .slice(0, 21)
    .join("\n");
  const samples = [];

  for (let iteration = 1; iteration <= ITERATIONS; iteration += 1) {
    const page = await browser.newPage();
    await page.goto(URL);
    await page.locator('[data-hydrated="true"]').waitFor({ state: "attached" });

    const started = performance.now();
    await page.locator("#file-upload").setInputFiles({
      name: `roster-20-${iteration}.csv`,
      mimeType: "text/csv",
      buffer: Buffer.from(csv),
    });
    await page.getByRole("heading", { name: "Roster Parsed Successfully" }).waitFor();
    await page.getByRole("button", { name: "Run Audit" }).click();
    await page.waitForURL(/\/runs\//);
    await page.getByRole("heading", { name: "Findings" }).waitFor();

    await page.getByRole("button", { name: "Run agents with live status" }).click();
    await page.getByText(/Finding hash sha256:/).waitFor({ timeout: 20_000 });

    let guard = 0;
    while (
      (await page.getByRole("button", { name: "Resolve this claim" }).count()) > 0 &&
      guard < 10
    ) {
      guard += 1;
      await page.getByRole("button", { name: "Resolve this claim" }).first().click();
      const drawer = page.getByRole("dialog");
      await drawer.getByRole("radio", { name: /downgrade/ }).check();
      await drawer.getByLabel("This claim dies if…").fill(FALSIFIER);
      const confirmed = page.waitForResponse(
        (response) =>
          response.url().includes("/resolutions") && response.request().method() === "POST",
      );
      await drawer.getByRole("button", { name: "Confirm resolution" }).click();
      await confirmed;
      await page.reload();
      await page.locator('[data-hydrated="true"]').waitFor({ state: "attached" });
    }

    await page.getByRole("button", { name: "Export statement" }).click();
    await page.waitForURL(/\/statement$/);
    await page.getByRole("heading", { name: "Evidence statement" }).waitFor();
    samples.push(performance.now() - started);
    await page.close();
  }

  const ordered = [...samples].sort((a, b) => a - b);
  const medianMs = Math.round(ordered[Math.floor(ordered.length / 2)]);
  const lines = [
    "# 20-row Hectic measurement",
    "",
    `Generated by \`npm run measure:time-saved\` on ${new Date().toISOString()}.`,
    "",
    `| Runs | Samples (ms) | Median |`,
    `|---:|---|---:|`,
    `| ${ITERATIONS} | ${samples.map((sample) => Math.round(sample)).join(", ")} | ${medianMs} ms (${(medianMs / 1000).toFixed(1)} s) |`,
    "",
    "The path includes a real CSV upload, preview, run creation, named agent",
    "stream, falsifier resolution and export. It uses the offline mock provider",
    "because a fresh clone must work without credentials.",
    "",
  ];
  writeFileSync(path.join("docs", "time-saved-measurement.md"), lines.join("\n"));
  console.log(`20-row median: ${medianMs} ms (${(medianMs / 1000).toFixed(1)} s)`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
} finally {
  await browser?.close().catch(() => {});
  server.kill("SIGTERM");
  await wait(250);
  if (!server.killed) server.kill("SIGKILL");
}
